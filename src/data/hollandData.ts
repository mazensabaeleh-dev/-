/**
 * Holland Hexagon distance & consistency calculation
 * In Holland's hexagon: R - I - A - S - E - C
 * Adjacent pairs (distance 1): highest consistency (e.g., R-I, I-A, A-S, S-E, E-C, C-R)
 * Alternate pairs (distance 2): medium consistency (e.g., R-A, I-S, A-E, S-C, E-R, C-I)
 * Opposite pairs (distance 3): low consistency (e.g., R-S, I-E, A-C)
 */
export const HEXAGON_ORDER: HollandDimensionCode[] = ['R', 'I', 'A', 'S', 'E', 'C'];

export function calculateHexagonDistance(c1: HollandDimensionCode, c2: HollandDimensionCode): number {
  const i1 = HEXAGON_ORDER.indexOf(c1);
  const i2 = HEXAGON_ORDER.indexOf(c2);
  const diff = Math.abs(i1 - i2);
  return Math.min(diff, 6 - diff);
}

export function getConsistencyDescription(c1: HollandDimensionCode, c2: HollandDimensionCode): {
  level: 'high' | 'medium' | 'low';
  title: string;
  explanation: string;
} {
  const dist = calculateHexagonDistance(c1, c2);
  if (dist === 1) {
    return {
      level: 'high',
      title: 'انسجام وتوافق مرتفع جداً (نمطان متجاوران في السداسي)',
      explanation:
        `النمط الأول (${HOLLAND_DIMENSIONS[c1].arabicName}) والنمط الثاني (${HOLLAND_DIMENSIONS[c2].arabicName}) متجاوران في نموذج هولاند السداسي، مما يعني تكاملاً وتجانساً كبيراً في الميول والمهارات ويسهل اختيار مسار مهني وأكاديمي واضح ومحدد.`
    };
  } else if (dist === 2) {
    return {
      level: 'medium',
      title: 'انسجام معتدل (نمطان متقاربان)',
      explanation:
        `النمطان (${HOLLAND_DIMENSIONS[c1].arabicName}) و (${HOLLAND_DIMENSIONS[c2].arabicName}) بينهما تباعد متوسط، مما يعكس اهتمامات متوازنة ومتعددة يمكن دمجها بنجاح في مجالات وتخصصات تجمع بين الجانبين.`
    };
  } else {
    return {
      level: 'low',
      title: 'اهتمامات متباينة ومتعددة (نمطان متقابلان)',
      explanation:
        `النمطان (${HOLLAND_DIMENSIONS[c1].arabicName}) و (${HOLLAND_DIMENSIONS[c2].arabicName}) متقابلان في السداسي، مما يشير إلى شخصية غنية ومتعددة المواهب يمكنها العمل في مجالات هجينة تجمع بين مجالات مختلفة وتبرع في التوفيق بين الأضداد.`
    };
  }
}
